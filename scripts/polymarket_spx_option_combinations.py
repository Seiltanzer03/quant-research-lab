#!/usr/bin/env python3
"""Retrospective Polymarket SPX + SPY option-combination audit.

READ-ONLY. Takes a PRIVATE archive generated by the prior user's v3 pipeline.
Only code and aggregated findings belong in this public repository.
Provider-level option quote times are unverified: NO EXECUTABLE EDGE CLAIM.
"""
from __future__ import annotations

import argparse
import io
import json
import zipfile
from pathlib import Path

import numpy as np
import pandas as pd

FEATURES = ["skew_rr", "atm_iv", "term_slope"]
SPEC = {
    "PM_calibrated": (),
    "Skew": ("skew",),
    "ATM_IV": ("iv",),
    "Term_Slope": ("term",),
    "Skew+IV": ("skew", "iv"),
    "Skew+IV+interaction": ("skew", "iv", "skew_x_iv"),
    "Skew+Term+interaction": ("skew", "term", "skew_x_term"),
    "IV+Term+interaction": ("iv", "term", "iv_x_term"),
    "3_main_effects": ("skew", "iv", "term"),
    "3_main+3_pairs": (
        "skew", "iv", "term", "skew_x_iv", "skew_x_term", "iv_x_term"
    ),
    "3_main+triple": ("skew", "iv", "term", "triple"),
    "Skew×PM_uncertainty": ("skew", "skew_x_uncertainty"),
}
MIN_TRAIN_DAYS = 8
RIDGE_PENALTY = 8.0
FEE_COEFFICIENT_SCENARIO = 0.04
MIN_THEORETICAL_EDGE_USD = 0.03


def sigmoid(z):
    return 1 / (1 + np.exp(-np.clip(z, -40, 40)))


def logit(p):
    p = np.clip(np.asarray(p, dtype=float), 1e-6, 1 - 1e-6)
    return np.log(p / (1 - p))


def load_private_daily(archive_path):
    with zipfile.ZipFile(archive_path) as archive:
        fname = next(
            (
                name
                for name in archive.namelist()
                if name.endswith("/tables/fixed_10am_snapshot_pm_15m_later.csv")
            ),
            None,
        )
        if fname is None:
            raise ValueError("Missing frozen 10am/15min private event input")
        df = pd.read_csv(io.BytesIO(archive.read(fname)))
    df = df.sort_values("date").reset_index(drop=True)
    fields = {
        "date", *FEATURES, "pm_yes_mid", "pm_yes_ask", "pm_no_ask",
        "actual_up", "expiry", "is_0dte", "ctx_source_age_minutes",
        "source_asof_verified", "created_ts", "pm_decision_ts",
    }
    if not fields.issubset(df.columns):
        raise ValueError(f"Missing columns {fields - set(df.columns)}")
    if len(df) != df.date.nunique() or len(df) != 20:
        raise ValueError("Requires exactly one event for each of 20 market days")
    if not (df.pm_decision_ts >= df.created_ts).all():
        raise ValueError("Decision preceded storage of option snapshot")
    if df[[*FEATURES, "pm_yes_mid", "actual_up"]].isna().any().any():
        raise ValueError("Missing option features or outcomes")
    if not df.pm_yes_mid.between(0.001, 0.999).all():
        raise ValueError("Invalid market probabilities")
    if not df.actual_up.isin([0, 1]).all():
        raise ValueError("Invalid binary outcomes")
    return df


def _design(train, test, terms):
    a = train[FEATURES].to_numpy(float)
    b = test[FEATURES].to_numpy(float)
    mu = a.mean(axis=0)
    sd = np.maximum(a.std(axis=0), [0.005, 0.005, 0.05])
    a = (a - mu) / sd
    b = (b - mu) / sd

    def components(x, pm):
        s, iv, t = x.T
        u = 4 * np.asarray(pm) * (1 - np.asarray(pm))
        return {
            "skew": s,
            "iv": iv,
            "term": t,
            "skew_x_iv": s * iv,
            "skew_x_term": s * t,
            "iv_x_term": iv * t,
            "triple": s * iv * t,
            "skew_x_uncertainty": s * u,
        }

    ca = components(a, train.pm_yes_mid.to_numpy())
    cb = components(b, test.pm_yes_mid.to_numpy())
    if not terms:
        return np.ones((len(train), 1)), np.ones((len(test), 1))
    xa = np.column_stack([ca[k] for k in terms])
    xb = np.column_stack([cb[k] for k in terms])
    for j, term in enumerate(terms):
        if "_x_" in term or term == "triple":
            m = xa[:, j].mean()
            scale = max(xa[:, j].std(), 0.2)
            xa[:, j] = (xa[:, j] - m) / scale
            xb[:, j] = (xb[:, j] - m) / scale
    return (
        np.column_stack([np.ones(len(train)), xa]),
        np.column_stack([np.ones(len(test)), xb]),
    )


def _fit(probability, outcomes, x, penalty=RIDGE_PENALTY):
    weights = np.zeros(x.shape[1])
    offset = logit(probability)
    y = np.asarray(outcomes, dtype=float)
    for _ in range(80):
        p = sigmoid(offset + x @ weights)
        grad = x.T @ (p - y) + penalty * weights
        h = (x.T * (p * (1 - p))) @ x + penalty * np.eye(x.shape[1])
        step = np.linalg.solve(h, grad)
        weights -= step
        if np.max(np.abs(step)) < 1e-11:
            break
    return weights


def walk_forward(df, min_train=MIN_TRAIN_DAYS):
    """Train strictly on days before the current target date."""
    rows = []
    for idx in range(min_train, len(df)):
        train, test = df.iloc[:idx], df.iloc[idx : idx + 1]
        r = test.iloc[0]
        for name, terms in SPEC.items():
            xtr, xte = _design(train, test, terms)
            weights = _fit(
                train.pm_yes_mid.to_numpy(),
                train.actual_up.to_numpy(),
                xtr,
            )
            p = float(sigmoid(logit(float(r.pm_yes_mid)) + xte[0] @ weights))
            yes_ask, no_ask = float(r.pm_yes_ask), float(r.pm_no_ask)
            yes_edge = (
                p - yes_ask
                - FEE_COEFFICIENT_SCENARIO * yes_ask * (1 - yes_ask)
            )
            no_edge = (
                1 - p - no_ask
                - FEE_COEFFICIENT_SCENARIO * no_ask * (1 - no_ask)
            )
            action, pnl = "PASS", 0.0
            if max(yes_edge, no_edge) > MIN_THEORETICAL_EDGE_USD:
                if yes_edge > no_edge:
                    action = "YES"
                    pnl = (
                        float(r.actual_up) - yes_ask
                        - FEE_COEFFICIENT_SCENARIO * yes_ask * (1 - yes_ask)
                    )
                else:
                    action = "NO"
                    pnl = (
                        1 - float(r.actual_up) - no_ask
                        - FEE_COEFFICIENT_SCENARIO * no_ask * (1 - no_ask)
                    )
            rows.append({
                "model": name,
                "date": r.date,
                "train_days": idx,
                "pm_yes_mid": float(r.pm_yes_mid),
                "p_model": p,
                "actual_up": int(r.actual_up),
                "expiry": str(r.expiry),
                "is_0dte": bool(r.is_0dte),
                "source_age_minutes": float(r.ctx_source_age_minutes),
                "source_asof_verified": bool(r.source_asof_verified),
                "model_brier": (p - float(r.actual_up)) ** 2,
                "pm_brier": (float(r.pm_yes_mid) - float(r.actual_up)) ** 2,
                "action": action,
                "net_usd_scenario": pnl,
            })
    return pd.DataFrame(rows)


def exact_signflip_p(differences):
    values = np.asarray(differences, dtype=float)
    n = len(values)
    bits = np.arange(2**n, dtype=np.uint32)[:, None]
    signs = np.where((bits >> np.arange(n)) & 1, 1, -1)
    means = (signs * values).mean(axis=1)
    return float(
        (1 + np.count_nonzero(np.abs(means) >= abs(values.mean()) - 1e-12))
        / (len(means) + 1)
    )


def summarize(p):
    baseline = p.loc[p.model == "PM_calibrated"].set_index("date")
    rows = []
    for name, group in p.groupby("model", sort=False):
        group = group.set_index("date").loc[baseline.index]
        diff = (group.model_brier - baseline.model_brier).to_numpy(float)
        trades = group.loc[group.action != "PASS"]
        good = group.loc[
            (group.source_age_minutes <= 60) & (~group.is_0dte)
        ]
        clean_diff = (good.model_brier - baseline.loc[good.index].model_brier)
        rows.append({
            "model": name,
            "independent_days": len(group),
            "pm_mid_brier": group.pm_brier.mean(),
            "pm_calibrated_brier": baseline.model_brier.mean(),
            "model_brier": group.model_brier.mean(),
            "delta_brier_vs_calibrated": diff.mean(),
            "raw_signflip_p_exploratory": exact_signflip_p(diff),
            "mean_without_two_best_days": np.delete(diff, np.argsort(diff)[:2]).mean(),
            "fresh_non0dte_eval_days": len(good),
            "fresh_non0dte_delta": clean_diff.mean() if len(good) else None,
            "hypothetical_trades": len(trades),
            "hypothetical_total_net_usd": trades.net_usd_scenario.sum(),
        })
    out = pd.DataFrame(rows).sort_values("delta_brier_vs_calibrated")
    names = [name for name in SPEC if name != "PM_calibrated"]
    matrix = np.stack([
        (
            p.loc[p.model == name].set_index("date")
            .loc[baseline.index].model_brier - baseline.model_brier
        ).to_numpy(float)
        for name in names
    ], axis=1)
    n = matrix.shape[0]
    bits = np.arange(2**n, dtype=np.uint32)[:, None]
    signs = np.where((bits >> np.arange(n)) & 1, 1, -1)
    max_abs = np.abs((signs @ matrix) / n).max(axis=1)
    for i, name in enumerate(names):
        observed = abs(matrix[:, i].mean())
        pvalue = (
            1 + np.count_nonzero(max_abs >= observed - 1e-12)
        ) / (len(max_abs) + 1)
        out.loc[out.model == name, "maxT_familywise_p_exploratory"] = pvalue
    return out


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--input-archive", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args(argv)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    daily = load_private_daily(args.input_archive)
    preds = walk_forward(daily)
    stats = summarize(preds)
    preds.to_csv(args.out_dir / "predictions.csv", index=False)
    stats.to_csv(args.out_dir / "comparison.csv", index=False)
    report = {
        "status": "RESEARCH_ONLY_NO_VERIFIED_EDGE",
        "n_historical_days": len(daily),
        "n_evaluated_independent_days": len(daily) - MIN_TRAIN_DAYS,
        "option_provider_asof_confirmed_count": int(
            daily.source_asof_verified.sum()
        ),
        "n_models_including_baseline": len(SPEC),
        "best_exploratory_model": stats.iloc[0].model,
        "best_exploratory_brier": float(stats.iloc[0].model_brier),
        "best_maxT_p": float(stats.iloc[0].maxT_familywise_p_exploratory),
        "not_untouched_oos": True,
        "fee_and_fills": "scenario only, actual fees and fills unverified",
        "original_private_inputs_not_published": True,
    }
    (args.out_dir / "summary.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
